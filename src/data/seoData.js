export const getLocalizedSeoData = (pageKey, lang = 'en') => {
  const data = staticSeoData[pageKey] || staticSeoData.home;
  const l = lang === 'ur' ? 'ur' : lang === 'ar' ? 'ar' : 'en';

  return {
    title: typeof data.title === 'object' ? (data.title[l] || data.title.en) : data.title,
    description: typeof data.description === 'object' ? (data.description[l] || data.description.en) : data.description,
    canonical: data.canonical,
    keywords: data.keywords,
    ogImage: data.ogImage,
    type: data.type || "website",
    noindex: data.noindex || false
  };
};

