/**
 * Returns localized course data merged with default course properties
 */
export const getLocalizedCourse = (course, language = 'en') => {
  if (!course) return null;
  const lang = language === 'ur' ? 'ur' : language === 'ar' ? 'ar' : 'en';
  
  const courseId = course.id || course.slug;
  const customLocalization = courseLocalizedData[courseId] || {};

  const title = customLocalization.title?.[lang] || 
    (lang === 'ar' && course.arabicTitle ? course.arabicTitle : (course.title?.[lang] || course.title || ''));

  const shortDescription = customLocalization.shortDescription?.[lang] ||
    (course.shortDescription?.[lang] || course.shortDescription || '');

  const fullDescription = customLocalization.fullDescription?.[lang] ||
    (course.fullDescription?.[lang] || course.fullDescription || shortDescription);

  const duration = customLocalization.duration?.[lang] ||
    (course.duration?.[lang] || course.duration || '');

  const learningMethod = customLocalization.learningMethod?.[lang] ||
    (course.learningMethod?.[lang] || course.learningMethod || '');

  const schedule = customLocalization.schedule?.[lang] ||
    (course.schedule?.[lang] || course.schedule || '');

  const categoryName = course.category;
  const category = categoryTranslations[categoryName]?.[lang] || categoryName;

  const badgeText = course.badge;
  const badge = badgeTranslations[badgeText]?.[lang] || badgeText;

  const audience = lang === 'ur' ? 'مرد اور خواتین' : lang === 'ar' ? 'للرجال والنساء' : 'Men & Women';

  return {
    ...course,
    title,
    shortDescription,
    fullDescription,
    category,
    originalCategory: course.category,
    badge,
    duration,
    learningMethod,
    schedule,
    audience
  };
};

export const getLocalizedCategoryName = (cat, lang = 'en') => {
  const l = lang === 'ur' ? 'ur' : lang === 'ar' ? 'ar' : 'en';
  return categoryTranslations[cat]?.[l] || cat;
};
